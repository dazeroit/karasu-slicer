# Anycubic Standard Resin from Photon Workshop's defaults (A11): printer, layer mm, bottom layers,
# transition layers, anti-aliasing, then for bottom and normal layers: exposure s, off time s and
# the motion bands from the plate up as (distance mm, speed mm/s), the same speed up and down.
ANYCUBIC_STAGED = [
    ("anycubic-photon-p1", 0.05, 1, 15, 16,
     (20.0, 30.0, [(5.0, 3.0), (5.0, 3.0)]),
     (2.0, 2.0, [(4.0, 3.0), (5.0, 8.0)])),
]
def two_stage_layer(exposure, rest, distances, up, down):
    """A layer lifting through two stages from the plate up at `up` mm/min, and retracting
    through them from the top down at `down` mm/min, as ELEGOO's tables write them."""
    near, far = distances
    return {
        "exposure_s": exposure,
        "wait_before_exposure_s": rest,
        "wait_after_exposure_s": 0.0,
        "wait_after_lift_s": 0.0,
        "pwm": 255,
        "lift": [{"distance_mm": near, "speed_mm_s": round(up[0] / 60, 6)},
                 {"distance_mm": far, "speed_mm_s": round(up[1] / 60, 6)}],
        "retract": [{"distance_mm": far, "speed_mm_s": round(down[0] / 60, 6)},
                    {"distance_mm": near, "speed_mm_s": round(down[1] / 60, 6)}],
    }


def layer(exposure, lift, lift_speed, retract_speed, light_off):
    return {
        "exposure_s": exposure,
        "wait_before_exposure_s": light_off,
        "wait_after_exposure_s": 0.0,
        "wait_after_lift_s": 0.0,
        "pwm": 255,
        "lift": [{"distance_mm": lift, "speed_mm_s": lift_speed}],
        "retract": [{"distance_mm": lift, "speed_mm_s": retract_speed}],
    }


def staged_layer(exposure, off_time, bands):
    """A layer whose plate leaves through the bands in order and comes back through them in
    reverse, so the retract stages list the bands from the top down."""
    def stages(order):
        return [{"distance_mm": d, "speed_mm_s": v} for d, v in order]
    return {
        "exposure_s": exposure,
        "wait_before_exposure_s": off_time,
        "wait_after_exposure_s": 0.0,
        "wait_after_lift_s": 0.0,
        "pwm": 255,
        "lift": stages(bands),
        "retract": stages(reversed(bands)),
    }


def image(antialias=1):
    return {"antialias": antialias, "min_gray": 0, "xy_compensation_px": 0,
            "bottom_xy_compensation_px": None}


def mm(um):
    """Micrometres as millimetres, without float noise or trailing zeros."""
    return f"{um / 1000:.6f}".rstrip("0").rstrip(".")


def printer_id(vendor, slug):
    return f"{vendor}-{slug}"


def setting(printer, resin, height, count, transitions, bottom, normal, status, source, sources,
            film=None, antialias=1):
    sid = f"{printer}-{resin}"
    if len(sid) > 64:
        raise SystemExit(f"{sid}: a profile identity has at most 64 bytes")
    return {
        "file": f"print-settings/{printer.split('-')[0]}/{printer.split('-', 1)[1]}/{resin}.json",
        "sources": sources,
        "document": {"kind": "print_setting", "profile": {
            "schema_version": 2,
            "id": sid,
            "name": f"Normal {height:g} mm",
            "revision": REVISION.get(sid, 1),
            "printer_id": printer,
            "resin_id": resin,
            "film": film,
            "status": status,
            "source": source,
            "based_on": None,
            "settings": {
                "layer_height_mm": height,
                "bottom_layer_count": count,
                "transition_layer_count": transitions,
                "bottom": bottom,
                "normal": normal,
            },
            "image": image(antialias),
        }},
    }


def entries():
    printers = []
    for vendor, slug, model, (px, py), (ux, uy), height, formats, src, release in PRINTERS:
        pid = printer_id(vendor, slug)
        mirror_x, mirror_y = ORIENTATION.get(pid, (False, False))
        vendor_name = next(name for v, name, *_ in VENDORS if v == vendor)
        printers.append({
            "file": f"printers/{vendor}/{slug}.json",
            "sources": src,
            "release": release,
            "orientation_verified": pid in ORIENTATION,
            "document": {"kind": "printer", "profile": {
                "schema_version": 2,
                "id": pid,
                "name": model.removeprefix(vendor_name + " "),
                "revision": REVISION.get(pid, 1),
                "build_size_mm": [round(px * ux / 1000, 6), round(py * uy / 1000, 6), float(height)],
                "resolution_px": [px, py],
                "origin_xy_mm": [0.0, 0.0],
                "swap_xy": False,
                "mirror_x": mirror_x,
                "mirror_y": mirror_y,
                "format_ids": formats,
                "limits": LIMITS,
                "vendor": vendor,
                "model": model,
                **({"fixed_layer_time_s": FIXED_LAYER_TIME_S[pid]}
                   if pid in FIXED_LAYER_TIME_S else {}),
            }},
        })
    resins, settings, report = resin_entries()
    return printers, resins, settings, report


def table(name):
    """The rows of a data file under catalog-data/ as dictionaries, its comment line skipped."""
    with open(DATA / name, encoding="utf-8") as f:
        lines = [line.rstrip("\n").split("\t") for line in f if not line.startswith("#")]
    return [dict(zip(lines[0], row)) for row in lines[1:]]


def quantity(text, unit, where):
    """A published value such as "2.5 s", "2.5s" or "4" (its unit left out) as a number, or
    None for "/", which marks a value the manufacturer does not give. Anything else stops the
    generator: it is not guessed at."""
    text = text.strip()
    if text == "/":
        return None
    match = re.fullmatch(rf"(\d+(?:\.\d+)?)\s*(?:{re.escape(unit)})?", text)
    if not match:
        raise SystemExit(f"{where}: cannot read {text!r} as {unit or 'a count'}")
    return float(match.group(1))


def published(text, where):
    """ELEGOO's single value or range "a-b" as (value, is_range): a range gives its middle."""
    text = text.strip()
    match = re.fullmatch(r"(\d+(?:\.\d+)?)(?:-(\d+(?:\.\d+)?))?", text)
    if not match:
        raise SystemExit(f"{where}: cannot read {text!r}")
    low = float(match.group(1))
    if match.group(2) is None:
        return low, False
    return round((low + float(match.group(2))) / 2, 3), True


def stages(text, where):
    """ELEGOO's two-stage value "a+b" as (a, b), or None for "/"."""
    if text.strip() == "/":
        return None
    match = re.fullmatch(r"(\d+(?:\.\d+)?)\+(\d+(?:\.\d+)?)", text.strip())
    if not match:
        raise SystemExit(f"{where}: cannot read {text!r} as two stages")
    return float(match.group(1)), float(match.group(2))


def material(vendor, slug, name, kind, density, sources, colour=None):
    rid = f"{vendor}-{slug}"
    return {
        "file": f"materials/{vendor}/{slug}.json",
        "sources": sources,
        "document": {"kind": "material", "profile": {
            "schema_version": 2,
            "id": rid,
            "name": name,
            "revision": REVISION.get(rid, 1),
            "vendor": vendor,
            "kind": kind,
            "density_g_per_ml": density,
            "cost_per_liter": None,
            "currency": None,
            "based_on": None,
            **({"colour": colour} if colour else {}),
        }},
    }


def resin_entries():
    """The resins and their print settings, and what the catalog's sources page reports about
    them: rows left out and colours whose settings differ from the entry's."""
    order = [printer_id(v, s) for v, s, *_ in PRINTERS]
    resins, settings = [], []
    report = {"anycubic_left_out": [], "anycubic_missing": [], "elegoo_colours": {},
              "elegoo_missing": []}

    # Anycubic (A8; the P1's Standard Resin from Photon Workshop, A11).
    columns = {}
    for names, slug, *_ in ANYCUBIC_RESINS:
        for column in names:
            columns[column] = f"anycubic-{slug}"
    a8 = {}
    for row in table("anycubic-a8.tsv"):
        rid = columns.get(row["resin"])
        if rid is None:
            continue
        key = (row["printer"], rid)
        if key in a8:
            raise SystemExit(f"{key}: two columns of Anycubic's page")
        a8[key] = row
    for printer, height, count, transitions, antialias, bottom, normal in ANYCUBIC_STAGED:
        settings.append(setting(
            printer, "anycubic-standard-resin", height, count, transitions,
            staged_layer(*bottom), staged_layer(*normal),
            "official", "Photon Workshop's default for this printer (A11)", "A11",
            film="NFEP", antialias=antialias))
    ranks = [f"anycubic-{slug}" for _, slug, *_ in ANYCUBIC_RESINS]
    for (printer, rid), row in sorted(
            a8.items(), key=lambda i: (order.index(i[0][0]), ranks.index(i[0][1]))):
        where = f"A8 {printer} {row['resin']}"
        if (printer, row["resin"]) in ANYCUBIC_LEFT_OUT:
            report["anycubic_left_out"].append(
                (printer, row["resin"], ANYCUBIC_LEFT_OUT[(printer, row["resin"])]))
            continue
        values = [quantity(row[c], u, where) for c, u in [
            ("layer", "mm"), ("exposure", "s"), ("light_off", "s"), ("bottom_exposure", "s"),
            ("bottom_layers", ""), ("lift", "mm"), ("lift_speed", "mm/s"),
            ("retract_speed", "mm/s")]]
        if None in values:
            report["anycubic_missing"].append((printer, rid))
            continue
        height, exposure, light_off, bottom, count, lift, up, down = values
        antialias = ANYCUBIC_ANTIALIAS.get(
            (printer, row["resin"]), ANYCUBIC_ANTIALIAS.get((printer, None)))
        if antialias is None:
            read = quantity(row["antialias"], "", where)
            antialias = 1 if read is None else int(read)
        settings.append(setting(
            printer, rid, height, int(count), 0,
            layer(bottom, lift, up, down, light_off), layer(exposure, lift, up, down, light_off),
            "official", "Anycubic's resin settings table (A8)", "A8", antialias=antialias))
    for names, slug, name, kind, density, sources in ANYCUBIC_RESINS:
        resins.append(material("anycubic", slug, name, kind, density, sources))

    # ELEGOO (E2, the manuals' bottom layers E3, the MSDS densities E9).
    e2 = {}
    for row in table("elegoo-e2.tsv"):
        e2.setdefault((row["printer"], row["resin"]), []).append(row)
    for names, slug, name, kind, principal, density in ELEGOO_RESINS:
        rid = f"elegoo-{slug}"
        differing = set()
        for printer in order:
            rows = [r for n in names for r in e2.get((printer, n), [])]
            if not printer.startswith("elegoo-"):
                continue
            if not rows:
                report["elegoo_missing"].append((printer, rid))
                continue
            main = [r for r in rows if r["colour"] == principal]
            if len(main) != 1:
                raise SystemExit(f"E2 {printer} {names[0]}: {len(main)} rows in {principal}")
            main = main[0]
            values = lambda r: [r[c] for c in ("bottom_exposure_s", "exposure_s", "layer_mm",
                                               "lift_mm", "lift_mm_min", "retract_mm_min",
                                               "rest_s")]
            differing |= {r["colour"] for r in rows if values(r) != values(main)}
            count = ELEGOO_BOTTOM_LAYERS.get(printer)
            if count is None:
                continue
            where = f"E2 row {main['row']}"
            bottom, bottom_range = published(main["bottom_exposure_s"], where)
            exposure, exposure_range = published(main["exposure_s"], where)
            height = quantity(main["layer_mm"], "", where)
            rest = quantity(main["rest_s"], "", where)
            distances = stages(main["lift_mm"], where)
            source = "ELEGOO's settings table (E2)"
            source += (", the middles of its ranges, and" if bottom_range or exposure_range
                       else " and")
            source += " the manual's bottom layers (E3)"
            if distances is None:
                lift, up, down = ELEGOO_TILT_LIFT[printer]
                bottom_layer = layer(bottom, lift, up, down, rest)
                normal_layer = layer(exposure, lift, up, down, rest)
                source += "; the printer tilts, and the lift is karasu-slicer's"
                status = "starting_point"
            else:
                up = stages(main["lift_mm_min"], where)
                down = stages(main["retract_mm_min"], where)
                bottom_layer = two_stage_layer(bottom, rest, distances, up, down)
                normal_layer = two_stage_layer(exposure, rest, distances, up, down)
                status = "starting_point" if bottom_range or exposure_range else "official"
            settings.append(setting(printer, rid, height, count, 0, bottom_layer, normal_layer,
                                    status, source, "E2, E3"))
        report["elegoo_colours"][rid] = (principal, sorted(differing))
        resins.append(material("elegoo", slug, name, kind, density,
                               "E2, E9" if density else "E2",
                               colour=principal if differing else None))

    # SUNLU: materials only.
    for slug, name, kind, density in SUNLU_RESINS:
        resins.append(material("sunlu", slug, name, kind, density,
                               "SU1, SU2" if density else "SU1"))
    return resins, settings, report


def write(path, document):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main():
    printers, materials, settings, report = entries()
    if ROOT.exists():
        shutil.rmtree(ROOT)
    for entry in printers + materials + settings:
        write(ROOT / entry["file"], entry["document"])
    index = {
        "schema_version": 1,
        "vendors": [{"id": v, "name": name, "website": site, "formats": formats,
                     **({"standard_resin": standard} if standard else {})}
                    for v, name, site, formats, standard in VENDORS],
        "printers": [{"file": e["file"], "release": e["release"],
                      "orientation_verified": e["orientation_verified"],
                      "sources": e["sources"]} for e in printers],
        "materials": [{"file": e["file"], "sources": e["sources"]} for e in materials],
        "print_settings": [{"file": e["file"], "sources": e["sources"]} for e in settings],
    }
    write(ROOT / "catalog.json", index)
    write_readme(materials, settings, report)
    write_rust(["catalog.json"] + [e["file"] for e in printers + materials + settings])


def write_rust(files):
    lines = [
        "//! The catalog's files, generated by `tools/assets/make_catalog.py`: do not edit by hand.",
        "",
        "/// Every catalog file as `(path under assets/catalog, contents)`.",
        "pub(super) const FILES: &[(&str, &str)] = &[",
    ]
    for f in files:
        lines += ["    (", f'        "{f}",', f'        include_str!("../../../../assets/catalog/{f}"),',
                  "    ),"]
    lines.append("];")
    RUST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    subprocess.run(["rustfmt", "--edition", "2021", "--config-path", str(REPO / "rustfmt.toml"),
                    str(RUST)], check=True)


def extension(format_id):
    """The file extension a format id writes, as users know it."""
    if format_id.startswith("anycubic-"):
        return "." + format_id.split("-")[1]
    return {"photon-v1-firmware-motion": ".photon", "goo-v3": ".goo"}.get(format_id, format_id)


def write_printer_table():
    """The README's table of supported printers, from PRINTERS, ORIENTATION and PRINTED."""
    rows = [
        TABLE_START,
        "| Vendor | Printer | File | Image orientation | Printed with karasu-slicer |",
        "| --- | --- | --- | --- | --- |",
    ]
    for vendor, slug, model, _px, _pitch, _height, formats, _src, _release in sorted(
            PRINTERS, key=lambda p: (p[0], p[2])):
        pid = printer_id(vendor, slug)
        vendor_name = next(name for v, name, *_ in VENDORS if v == vendor)
        files = ", ".join(dict.fromkeys(extension(f) for f in formats))
        verified = "verified" if pid in ORIENTATION else "not verified"
        printed = f"yes ({PRINTED[pid]})" if pid in PRINTED else "not yet"
        rows.append(f"| {vendor_name} | {model.removeprefix(vendor_name + ' ')} | {files} |"
                    f" {verified} | {printed} |")
    rows.append(TABLE_END)
    text = README.read_text(encoding="utf-8")
    start, end = text.index(TABLE_START), text.index(TABLE_END) + len(TABLE_END)
    README.write_text(text[:start] + "\n".join(rows) + text[end:], encoding="utf-8")


